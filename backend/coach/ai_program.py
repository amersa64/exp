# Sets/reps per (goal_domain, slot_class). Lower reps + more sets for the
# main lift, higher reps + fewer sets for accessories. The LLM doesn't pick
# these — it only picks the exercise name and the slot label; numbers come
# from this table.
#
# slot_class is the leading word of the LLM's slot string ("primary_compound",
# "secondary_compound", "accessory_N", "stretch"). We coerce unknown slots
# to "accessory" so a wonky slot label still gets reasonable defaults.
_SETS_REPS: dict[tuple[str, str], tuple[int, int]] = {
    # strength — heavier and lower-rep across the board
    ("strength",     "primary"):   (5, 5),
    ("strength",     "secondary"): (3, 5),
    ("strength",     "accessory"): (3, 8),
    # hypertrophy — classic 8-12 range, more volume on accessories
    ("hypertrophy",  "primary"):   (4, 6),
    ("hypertrophy",  "secondary"): (4, 8),
    ("hypertrophy",  "accessory"): (3, 12),
    # conditioning / weight loss — moderate sets, higher reps to keep heart rate up
    ("conditioning", "primary"):   (3, 8),
    ("conditioning", "secondary"): (3, 10),
    ("conditioning", "accessory"): (3, 15),
    # longevity — gentle, volume over intensity
    ("longevity",    "primary"):   (3, 10),
    ("longevity",    "secondary"): (2, 12),
    ("longevity",    "accessory"): (2, 12),
    # discipline — 75-Hard style, lots of volume
    ("discipline",   "primary"):   (4, 8),
    ("discipline",   "secondary"): (3, 10),
    ("discipline",   "accessory"): (3, 12),
}


def _classify_slot(slot_label: str) -> str:
    """LLM slot label → one of {primary, secondary, accessory}.

    The picker prompt teaches the LLM to use slot strings like
    "primary_compound", "secondary_compound", "accessory_1". We look at the
    leading token. Unknown labels default to "accessory" (the safe choice —
    smaller load, won't hurt anyone).
    """
    head = slot_label.split("_", 1)[0].lower()
    if head == "primary":
        return "primary"
    if head == "secondary":
        return "secondary"
    return "accessory"


# Heuristic mapper from picked exercise name → canonical calibration slot.
# Used to derive a starting load from the user's measured 1RM when we can.
# Conservative: we'd rather return None and have the user feel out the
# weight than guess wrong and prescribe something dangerous. Order matters —
# more specific patterns must come before more generic ones (deadlift before
# squat etc.).
def _calibration_slot_for(exercise: Exercise) -> str | None:
    n = exercise.name.lower()
    pm = {m.lower() for m in exercise.primary_muscles}
    # Deadlift family — name match is reliable.
    if "deadlift" in n:
        return "deadlift"
    # Squat family — distinguish from leg press / split squat by primary muscle.
    if "squat" in n and "quadriceps" in pm:
        return "squat"
    # Bench family — must be a bench press, not a fly/extension.
    if "bench press" in n:
        return "bench"
    # Overhead press family.
    if ("military press" in n or "overhead press" in n
            or "shoulder press" in n or n.startswith("standing dumbbell press")):
        return "ohp"
    # Row family — barbell/dumbbell rows.
    if "row" in n and ("middle back" in pm or "lats" in pm):
        return "row"
    return None


# Scale factors per slot class — fraction of the canonical-slot working
# load to prescribe. Primary = full working load (whatever the persona's
# progression has earned). Secondary = lighter to manage fatigue. Accessory
# = even lighter, focus on tempo/control. Loads are rounded to the nearest
# 5 lb for plate practicality.
_LOAD_SCALE: dict[str, float] = {
    "primary":   1.00,
    "secondary": 0.85,
    "accessory": 0.70,
}


def _load_for_pick(
    exercise: Exercise,
    slot_class: str,
    progression: dict[str, float | int],
) -> float | None:
    """Best-effort load. None for unmappable picks — user fills it in."""
    slot = _calibration_slot_for(exercise)
    if slot is None:
        return None
    canonical = progression.get(f"{slot}_lb")
    if canonical is None:
        return None
    scaled = float(canonical) * _LOAD_SCALE.get(slot_class, 0.70)
    # Round to nearest 5 lb so the prescription reads like a real plate load.
    return round(scaled / 5) * 5


def render_session_from_ai_program(
    ai_program: "AIProgram",
    session_index: int,
    goal_domain: str,
    progression: dict[str, float | int],
    fallback: Session,
) -> Session:
    """Convert one day of the AIProgram into the existing Session shape.

    session_index rotates through the days array. The fallback is used when
    the AIProgram has nothing for this day (validation stripped it) or this
    day is a recovery day with no training exercises — caller still gets a
    valid Session.

    Sets/reps come from the (goal, slot_class) table. Loads come from the
    persona's progression dict (calibration-derived) when the picked
    exercise maps to a canonical slot; otherwise None (user enters weight
    themselves at log time).
    """
    if not ai_program.days:
        return fallback
    day = ai_program.days[session_index % len(ai_program.days)]

    # Recovery day → render the canned stretching block. No fallback to the
    # persona session here, because the recovery day exists *as* the day —
    # we don't want to overlay a strength session on top.
    if day.spec.kind == "recovery":
        return _render_recovery_session(day)

    if not day.exercises:
        return fallback

    rxs: list[ExercisePrescription] = []
    from .exercises import catalog as _cat
    cat = _cat()
    for pick in day.exercises:
        slot_class = _classify_slot(pick.slot)
        sets, reps = _SETS_REPS.get((goal_domain, slot_class), (3, 10))
        ex = cat.get(pick.catalog_name)
        load = _load_for_pick(ex, slot_class, progression) if ex else None
        rxs.append(ExercisePrescription(
            name=pick.catalog_name,
            sets=sets,
            reps=reps,
            load_lb=load,
            notes=pick.rationale,
        ))
    return Session(
        name=day.spec.name,
        summary=f"AI-built · {day.spec.pattern_focus}",
        expected_minutes=day.spec.target_minutes,
        progression_rule=fallback.progression_rule,
        exercises=rxs,
    )


def _render_recovery_session(day: "DayPlan") -> Session:
    """Stretches + mobility for a non-training day.

    Picks come from the catalog's stretching category, deterministically
    chosen to hit common tight areas (hips, hamstrings, t-spine, shoulders).
    No LLM call needed — stretching routines don't benefit much from
    personalization at this layer.
    """
    from .exercises import catalog as _cat
    cat = _cat()
    target_muscles = ["hamstrings", "quadriceps", "glutes", "lats", "chest"]
    picks: list[ExercisePrescription] = []
    seen: set[str] = set()
    for muscle in target_muscles:
        for ex in cat.find(category="stretching", primary_muscle=muscle):
            key = ex.name.lower()
            if key in seen:
                continue
            seen.add(key)
            picks.append(ExercisePrescription(
                name=ex.name,
                sets=1,
                reps=1,
                load_lb=None,
                notes=ex.first_instruction() or "Hold the stretch, breathe slow.",
                duration_min=1,
            ))
            break
        if len(picks) >= 5:
            break
    return Session(
        name=day.spec.name or "Recovery & Mobility",
        summary=f"Active recovery · {day.spec.pattern_focus or 'mobility'}",
        expected_minutes=day.spec.target_minutes,
        progression_rule="Hold each stretch ~60 seconds. No bouncing. Stop if anything sharp.",
        exercises=picks,
    )


def _coerce_int(v: Any, default: int) -> int:
    if isinstance(v, int):
        return v
    if isinstance(v, str) and v.strip().isdigit():
        return int(v.strip())
    return default


def _coerce_level(v: Any) -> str | None:
    """Map free-text experience → catalog level vocabulary."""
    if not v:
        return None
    s = str(v).lower()
    if "advanced" in s or "expert" in s:
        return "expert"
    if "intermediate" in s or "1+" in s or "2+" in s:
        return "intermediate"
    if "novice" in s or "beginner" in s or "new" in s or "none" in s:
        return "beginner"
    return None
